// vendor/hanzi-mmah/mmah.json (APL) → src/recognition/offline/hanzi-data.generated.ts (compact, same values)
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';

const raw = readFileSync('vendor/hanzi-mmah/mmah.json');
const sha = createHash('sha256').update(raw).digest('hex');
if (sha !== '287943446fe52cef43df1ba47619a3c040e5924b6031b90939e880711dbc70ae') throw new Error(`unexpected mmah.json ${sha}`);
const d = JSON.parse(raw.toString('utf8'));
const sub = Buffer.from(d.substrokes, 'base64');
// GB2312 levels from the code table (level 1: rows 0xB0–0xD7, level 2: rows 0xD8–0xF7)
const gb = new Map();
const dec = new TextDecoder('gb2312');
for (let r = 0xb0; r <= 0xf7; r++)
  for (let c = 0xa1; c <= 0xfe; c++) {
    const ch = dec.decode(new Uint8Array([r, c]));
    if (ch.length === 1 && ch !== '�') gb.set(ch, r <= 0xd7 ? 1 : 2);
  }
const n = d.chars.length;
const chars = [];
const head = new Uint8Array(n * 3);
const parts = [];
let total = 0;
d.chars.forEach(([ch, strokes, subs, off], i) => {
  if (subs > 255 || strokes > 255) throw new Error('count too large');
  chars.push(ch);
  head[i] = strokes;
  head[n + i] = subs;
  head[2 * n + i] = gb.get(ch) ?? 0;
  parts.push(sub.subarray(off, off + subs * 3));
  total += subs * 3;
});
const body = Buffer.concat([Buffer.from(head), ...parts.map((p) => Buffer.from(p))]);
const apl = readFileSync('vendor/hanzi-mmah/LICENSE-APL.txt', 'utf8');
const out = `/* eslint-disable */
// GENERATED by scripts/build-hanzi-data.mjs — do not edit.
// Stroke templates of ${n} Chinese characters (sub-stroke sequences), converted without changing values
// from Make Me a Hanzi / HanziLookupJS "mmah.json" (sha256 ${sha}).
// Licensed under the Arphic Public License (text below) — see vendor/hanzi-mmah/README.md.
${'/*!'} Make Me a Hanzi stroke data (via HanziLookupJS "mmah.json"), Arphic Public License.
 * Modified by HandNote on 2026-10-20: converted from JSON to a packed binary table (values unchanged)
 * and a GB2312 level flag added per character (vendor/hanzi-mmah/README.md, modification notice).
 * The licence text follows unaltered (APL section 1).
 *
${apl.trimEnd().split('\n').map((l) => (' * ' + l).trimEnd()).join('\n')}
 */
export const HANZI_CHARS = ${JSON.stringify(chars.join(''))};
export const HANZI_COUNT = ${n};
/** [strokeCount × n][subStrokeCount × n][gb2312Level × n][sub-strokes: direction, length, centre(x<<4|y) × 3 bytes] */
export const HANZI_DATA_B64 = ${JSON.stringify(body.toString('base64'))};
export const HANZI_LICENSE = ${JSON.stringify(apl)};
`;
writeFileSync('src/recognition/offline/hanzi-data.generated.ts', out);
console.log(`chars ${n}, sub-stroke bytes ${total}, gb2312 L1 ${[...head.subarray(2 * n)].filter((x) => x === 1).length}, L2 ${[...head.subarray(2 * n)].filter((x) => x === 2).length}, file ${out.length} B`);
