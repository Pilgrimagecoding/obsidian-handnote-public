#!/usr/bin/env node
/**
 * Dev-time generator of src/local/font-pack.generated.ts: the Excalidraw hand-drawn fonts
 * (Excalifont — Latin/Cyrillic/Greek, Xiaolai — CJK; both SIL OFL 1.1) as subset files with their
 * unicode ranges, sizes and SHA-256, pinned to one excalidraw commit.
 *
 *   node scripts/build-font-pack.mjs <path to an excalidraw checkout>
 *
 * Nothing is bundled: HandNote downloads the subsets on request into this device's storage.
 */
import { readFileSync, readdirSync, writeFileSync, statSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { execSync } from 'node:child_process';
import { join } from 'node:path';

const root = process.argv[2];
if (!root) throw new Error('pass the excalidraw checkout path');
const commit = execSync('git rev-parse HEAD', { cwd: root }).toString().trim();
const out = [];
for (const [fam, dir] of [['excalifont', 'Excalifont'], ['xiaolai', 'Xiaolai']]) {
  const base = join(root, 'packages/excalidraw/fonts', dir);
  const src = readFileSync(join(base, 'index.ts'), 'utf8');
  const imports = new Map([...src.matchAll(/import (_\d+) from "\.\/([^"]+\.woff2)";/g)].map((m) => [m[1], m[2]]));
  for (const m of src.matchAll(/uri:\s*(_\d+),\s*descriptors:\s*\{\s*unicodeRange:\s*"([^"]+)"/g)) {
    const file = imports.get(m[1]);
    const data = readFileSync(join(base, file));
    out.push({ family: fam, name: file, bytes: data.length, sha256: createHash('sha256').update(data).digest('hex'), range: m[2] });
  }
  if (out.filter((x) => x.family === fam).length !== readdirSync(base).filter((f) => f.endsWith('.woff2')).length) throw new Error(`${dir}: not every file has a range`);
}
const total = out.reduce((a, f) => a + f.bytes, 0);
writeFileSync(
  'src/local/font-pack.generated.ts',
  `// Generated by scripts/build-font-pack.mjs from excalidraw@${commit} — do not edit.\n` +
    `// Excalifont (Excalidraw; Virgil by Your Own Font Foundry) and Xiaolai (LXGW): SIL Open Font License 1.1.\n` +
    `export const FONT_COMMIT = ${JSON.stringify(commit)};\n` +
    `export const FONT_FILES: { family: 'excalifont' | 'xiaolai'; name: string; bytes: number; sha256: string; range: string }[] = ${JSON.stringify(out)};\n`,
);
console.log(`${out.length} subsets, ${(total / 1048576).toFixed(1)} MB, excalidraw@${commit.slice(0, 7)}`);
