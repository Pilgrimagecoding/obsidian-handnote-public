// Since 0.8.0-beta.3: ship ONNX Runtime Web inside main.js instead of downloading it at runtime (Obsidian maintainers: plugins should not install dependencies;
// bundling the WASM is preferred).
//
// Writes src/local/ort-embedded.generated.ts (git-ignored) with the two runtime files of the
// "runtime" pack — the SAME version and the SAME bytes as before (checked against the SHA-256 pinned
// in src/local/manifest.ts) — gzip-compressed and base64-encoded, each inside a function so the
// string is only materialised when local recognition starts.
//
// Source of the files, first found:
//   1. node_modules/onnxruntime-web/dist/   (npm install -D -E onnxruntime-web@1.24.2)
//   2. local-assets/ort/dist/              (scripts/fetch-local-assets.mjs)
// HN_EMBED_ORT=0 writes a stub instead (the stable behaviour: runtime downloaded on request).
import { createHash } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { gzipSync } from 'node:zlib';

const FILES = ['ort.wasm.bundle.min.mjs', 'ort-wasm-simd-threaded.wasm'];
const OUT = 'src/local/ort-embedded.generated.ts';

function pinned() {
  const src = readFileSync('src/local/manifest.ts', 'utf8');
  const ver = src.match(/ORT_VERSION\s*=\s*'([^']+)'/)?.[1];
  const pins = {};
  for (const name of FILES) {
    const m = src.match(new RegExp(`name: '${name.replace(/\./g, '\\.')}', bytes: (\\d+), sha256: '([0-9a-f]{64})'`));
    if (!m) throw new Error(`no pin for ${name} in src/local/manifest.ts`);
    pins[name] = { bytes: Number(m[1]), sha256: m[2] };
  }
  return { ver, pins };
}

export function buildEmbeddedOrt({ write = true } = {}) {
  const enabled = process.env.HN_EMBED_ORT !== '0';
  let out;
  let info;
  if (!enabled) {
    out = `// Generated by scripts/build-embedded-ort.mjs (HN_EMBED_ORT=0) — do not edit.\nexport const ORT_EMBEDDED = null;\n`;
    info = 'runtime NOT embedded (HN_EMBED_ORT=0)';
  } else {
    const { ver, pins } = pinned();
    const dirs = ['node_modules/onnxruntime-web/dist', 'local-assets/ort/dist'];
    const dir = dirs.find((d) => FILES.every((f) => existsSync(`${d}/${f}`)));
    if (!dir) throw new Error(`ONNX Runtime Web ${ver} files not found in ${dirs.join(' or ')} (npm install -D -E onnxruntime-web@${ver})`);
    const parts = [];
    const meta = [];
    for (const [i, name] of FILES.entries()) {
      const data = readFileSync(`${dir}/${name}`);
      const sha = createHash('sha256').update(data).digest('hex');
      if (data.length !== pins[name].bytes || sha !== pins[name].sha256) throw new Error(`${dir}/${name}: ${data.length} B ${sha} does not match the pinned ${pins[name].bytes} B ${pins[name].sha256}`);
      // gzip from Node's zlib with mtime 0: the same input gives the same bytes on every build
      const gz = gzipSync(data, { level: 9 });
      meta.push(`  { name: ${JSON.stringify(name)}, bytes: ${data.length}, sha256: ${JSON.stringify(sha)}, gzBytes: ${gz.length}, data: f${i} },`);
      parts.push(`function f${i}(): string {\n  return ${JSON.stringify(gz.toString('base64'))};\n}`);
    }
    const licence = `/*! ONNX Runtime Web ${ver} (onnxruntime-web), built into HandNote unmodified (gzip + base64).\n * MIT License\n *\n * Copyright (c) Microsoft Corporation\n *\n * Permission is hereby granted, free of charge, to any person obtaining a copy\n * of this software and associated documentation files (the "Software"), to deal\n * in the Software without restriction, including without limitation the rights\n * to use, copy, modify, merge, publish, distribute, sublicense, and/or sell\n * copies of the Software, and to permit persons to whom the Software is\n * furnished to do so, subject to the following conditions:\n *\n * The above copyright notice and this permission notice shall be included in all\n * copies or substantial portions of the Software.\n *\n * THE SOFTWARE IS PROVIDED "AS IS", WITHOUT WARRANTY OF ANY KIND, EXPRESS OR\n * IMPLIED, INCLUDING BUT NOT LIMITED TO THE WARRANTIES OF MERCHANTABILITY,\n * FITNESS FOR A PARTICULAR PURPOSE AND NONINFRINGEMENT. IN NO EVENT SHALL THE\n * AUTHORS OR COPYRIGHT HOLDERS BE LIABLE FOR ANY CLAIM, DAMAGES OR OTHER\n * LIABILITY, WHETHER IN AN ACTION OF CONTRACT, TORT OR OTHERWISE, ARISING FROM,\n * OUT OF OR IN CONNECTION WITH THE SOFTWARE OR THE USE OR OTHER DEALINGS IN THE\n * SOFTWARE.\n *\n * Third-party components of ONNX Runtime:\n * https://github.com/microsoft/onnxruntime/blob/v${ver}/ThirdPartyNotices.txt\n */`;
    out = `// Generated by scripts/build-embedded-ort.mjs from onnxruntime-web ${ver} — do not edit.\n${licence}\n${parts.join('\n')}\nexport const ORT_EMBEDDED: { version: string; files: { name: string; bytes: number; sha256: string; gzBytes: number; data: () => string }[] } | null = {\n  version: ${JSON.stringify(ver)},\n  files: [\n${meta.join('\n')}\n  ],\n};\n`;
    info = `runtime embedded from ${dir}: ${FILES.join(', ')}`;
  }
  const changed = !existsSync(OUT) || readFileSync(OUT, 'utf8') !== out;
  if (write && changed) writeFileSync(OUT, out);
  return { changed, info, bytes: out.length };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const r = buildEmbeddedOrt();
  console.log(`${r.info} (${(r.bytes / 1048576).toFixed(2)} MB source)${r.changed ? ' (updated)' : ''}`);
}
